"""Write or verify the committed GNN specification for the grid-world model.

The document under ``specs/`` is generated from the implementation so the
declared matrices cannot drift from the runtime model:

    uv run python scripts/export_gnn_spec.py           # write
    uv run python scripts/export_gnn_spec.py --check   # verify (release gate)

The pinned upstream parser validation is a separate, explicit step:
``uv run python scripts/validate_gnn_spec.py`` (see ``docs/gnn.md``).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from blockference.gnn import GNN_SPEC_PATH, render_spec


def check(path: Path = GNN_SPEC_PATH) -> list[str]:
    """Return drift descriptions for a committed document that is stale."""

    expected = render_spec()
    if not path.is_file():
        return [f"missing GNN specification: {path}"]
    committed = path.read_text(encoding="utf-8")
    if committed == expected:
        return []
    return [f"{path} differs from the document generated by blockference.gnn.render_spec"]


def main(argv: list[str] | None = None) -> int:
    """Write the document, or verify it with ``--check``."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    parser.add_argument("--path", type=Path, default=GNN_SPEC_PATH)
    args = parser.parse_args(argv)
    if args.check:
        drift = check(args.path)
        if drift:
            print("GNN specification drift:", file=sys.stderr)
            for item in drift:
                print(f"  {item}", file=sys.stderr)
            return 1
        print(f"GNN specification current: {args.path}")
        return 0
    args.path.parent.mkdir(parents=True, exist_ok=True)
    args.path.write_text(render_spec(), encoding="utf-8")
    print(f"wrote {args.path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
