"""Write the generated gate metrics document.

The numbers in ``docs/_generated/gate-metrics.md`` come from recorded receipts:

* ``gate-timings.json`` -- one run of the canonical gate (``--timings``);
* ``gate-baseline.json`` -- pre-change receipts imported with
  ``--record-baseline`` (repeat for disjoint arm selections).

The producer never invents a runtime: an arm missing from a receipt is reported
as not recorded. Test counts are derived from the current suite with
``pytest --collect-only``.

Refresh after changing the gate or the test selection::

    uv run python scripts/release_check.py --arm all --arm test --arm render \
        --timings /tmp/gate-after.json
    uv run python scripts/gate_metrics.py --record-timings /tmp/gate-after.json
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECEIPT = ROOT / "docs" / "_generated" / "gate-timings.json"
BASELINE = ROOT / "docs" / "_generated" / "gate-baseline.json"
OUTPUT = ROOT / "docs" / "_generated" / "gate-metrics.md"
SCHEMA = "activeblockference-gate/v1"
BASELINE_SCHEMA = "activeblockference-gate-baseline/v1"
FAST_SELECTION = "not slow"

ARM_ORDER = (
    "lint",
    "types",
    "test",
    "test-full",
    "docs",
    "manuscript",
    "gnn",
    "smoke",
    "package",
    "render",
)


def _collected(*extra: str) -> int:
    """Return the number of tests selected by ``pytest --collect-only``."""

    result = subprocess.run(
        ["uv", "run", "pytest", "--collect-only", "-q", *extra],
        cwd=ROOT,
        check=True,
        text=True,
        capture_output=True,
    )
    return sum(1 for line in result.stdout.splitlines() if "::" in line)


def _receipt() -> dict[str, object]:
    """Return the recorded gate receipt, failing when it is absent or unknown."""

    if not RECEIPT.is_file():
        raise FileNotFoundError(
            f"missing gate receipt {RECEIPT.relative_to(ROOT)}; run "
            "scripts/release_check.py --timings docs/_generated/gate-timings.json"
        )
    payload = json.loads(RECEIPT.read_text(encoding="utf-8"))
    if payload.get("schema") != SCHEMA:
        raise ValueError(f"unsupported gate receipt schema {payload.get('schema')!r}")
    return payload


def _baseline() -> dict[str, object]:
    """Return the recorded pre-change baseline, or an empty record."""

    if not BASELINE.is_file():
        return {}
    payload = json.loads(BASELINE.read_text(encoding="utf-8"))
    if payload.get("schema") != BASELINE_SCHEMA:
        raise ValueError(f"unsupported baseline schema {payload.get('schema')!r}")
    return payload


def _load_run(path: Path) -> dict[str, object]:
    """Read an actual gate run, retaining both passing and failing observations."""

    payload = json.loads(path.read_text(encoding="utf-8"))
    if payload.get("schema") != SCHEMA or not isinstance(payload.get("arms"), dict):
        raise ValueError(f"not a gate run receipt: {path}")
    for arm, recorded in payload["arms"].items():
        if arm not in ARM_ORDER or recorded.get("status") not in {"passed", "failed"}:
            raise ValueError(f"invalid arm observation in {path}: {arm}")
        if not isinstance(recorded.get("seconds"), (int, float)) or recorded["seconds"] < 0:
            raise ValueError(f"invalid arm wall time in {path}: {arm}")
    return payload


def _record_baseline(paths: list[Path]) -> None:
    """Combine disjoint measured selections without changing their observations."""

    runs = [_load_run(path) for path in paths]
    first = runs[0]
    arms: dict[str, object] = {}
    for run in runs:
        if (run.get("host"), run.get("python")) != (first.get("host"), first.get("python")):
            raise ValueError("baseline selections must share a host and interpreter")
        if arms.keys() & run["arms"].keys():
            raise ValueError("baseline selections overlap; retain one observation per arm")
        arms.update(run["arms"])
    baseline = {
        "schema": BASELINE_SCHEMA,
        "measured": first["generated"],
        "host": first["host"],
        "python": first["python"],
        "conditions": (
            "One run per arm before this estate change on the same host and interpreter. "
            "Warm caches and host load are uncontrolled; failed observations are retained. "
            "The render arm was measured separately after the package cache miss."
        ),
        "runs": runs,
        "arms": arms,
    }
    BASELINE.write_text(json.dumps(baseline, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def render(payload: dict[str, object], baseline: dict[str, object]) -> str:
    """Render the metrics document from the recorded receipts."""

    arms = payload.get("arms") or {}
    before = baseline.get("arms") or {}
    tests = payload.get("tests") or {}
    lines = [
        "# Gate metrics",
        "",
        "<!-- Generated by scripts/gate_metrics.py; edit the script, not this file. -->",
        "",
        "Measured wall times from recorded canonical gate observations on "
        f"`{payload.get('host')}` with Python {payload.get('python')} at "
        f"`{payload.get('generated')}`.",
        "",
        str(payload.get("conditions", "One observation per arm; host load and caches are uncontrolled.")),
        "",
        "Refresh with:",
        "",
        "```bash",
        "uv run python scripts/release_check.py --arm all --arm test --arm render \\",
        "    --timings /tmp/gate-after.json",
        "uv run python scripts/gate_metrics.py --record-timings /tmp/gate-after.json",
        "```",
        "",
        "## Before and after",
        "",
        "`n/a` means no baseline observation was recorded. Failed baselines are not "
        "comparable to passing runs. No speedup is inferred from these single samples.",
        "",
        "| Arm | Before (s) | Before status | After (s) | After status | After command |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for arm in ARM_ORDER:
        recorded = before.get(arm) or {}
        current = arms.get(arm) or {}
        before_seconds = recorded.get("seconds", "n/a")
        before_status = recorded.get("status", "not recorded")
        after_seconds = current.get("seconds", "not recorded")
        status = current.get("status", "—")
        commands = current.get("commands") or []
        command = f"`{commands[0]}`" if commands else "—"
        lines.append(
            f"| `{arm}` | {before_seconds} | {before_status} | {after_seconds} | {status} | {command} |"
        )
    notes = [
        f"- `{arm}`: {recorded['note']}"
        for arm, recorded in before.items()
        if recorded.get("note") and not recorded.get("comparable", True)
    ]
    notes.extend(
        f"- `{arm}` failed: {recorded['error']}"
        for arm, recorded in before.items()
        if recorded.get("status") == "failed" and recorded.get("error")
    )
    if notes:
        lines += [
            "",
            "Baseline workloads that are not equivalent to their arms:",
            "",
            *notes,
        ]
    if baseline:
        lines += [
            "",
            "Baseline conditions: " + str(baseline.get("conditions", "")),
            "",
            "The baseline and current receipts are historical evidence. Timings "
            "include host load and warm caches; they are not a controlled benchmark.",
        ]
    lines += ["", "## Test selection", "", "| Selection | Collected tests |", "| --- | --- |"]
    total = _collected()
    slow = _collected("-m", "slow")
    lines.append(f"| full suite | {total} |")
    lines.append(f'| fast (`-m "{FAST_SELECTION}"`) | {total - slow} |')
    lines.append(f"| slow (`-m slow`) | {slow} |")
    lines += [
        "",
        f"Recorded run: {tests.get('passed', 'not recorded')} passed, "
        f"{tests.get('skipped', 'not recorded')} skipped.",
        "",
    ]
    coverage = tests.get("coverage_percent")
    if coverage is None:
        lines.append("Coverage was not recorded by the receipt.")
    else:
        lines.append(
            f"`test-full` recorded {coverage}% line coverage of `blockference` (floor 90%)."
        )
    lines += [
        "",
        "## Receipts",
        "",
        "The current numbers come from [`gate-timings.json`](gate-timings.json), "
        "written by `scripts/release_check.py --timings`; the before numbers come "
        "from [`gate-baseline.json`](gate-baseline.json), imported from actual runs with "
        "`scripts/gate_metrics.py --record-baseline <receipt>` (repeat for disjoint arms). "
        "An arm absent from a receipt is reported as not recorded, never as passing.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Write the metrics document, or verify it with ``--check``."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the document is stale")
    parser.add_argument(
        "--record-baseline", type=Path, action="append", default=[],
        help="import a pre-change gate receipt; repeat for disjoint arm selections",
    )
    parser.add_argument("--record-timings", type=Path, help="import a post-change gate receipt")
    args = parser.parse_args(argv)
    if args.check and (args.record_baseline or args.record_timings):
        parser.error("--check cannot import receipts")
    try:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        if args.record_baseline:
            _record_baseline(args.record_baseline)
        if args.record_timings:
            _load_run(args.record_timings)
            if args.record_timings.resolve() != RECEIPT.resolve():
                shutil.copyfile(args.record_timings, RECEIPT)
        content = render(_receipt(), _baseline())
    except (FileNotFoundError, ValueError, subprocess.CalledProcessError) as exc:
        print(f"gate metrics failed: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if not OUTPUT.is_file():
            print(f"gate metrics failed: missing {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        if OUTPUT.read_text(encoding="utf-8") != content:
            print(
                "gate metrics drift: run uv run python scripts/gate_metrics.py to refresh "
                f"{OUTPUT.relative_to(ROOT)}",
                file=sys.stderr,
            )
            return 1
        print("gate metrics check passed")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
