"""Write the generated gate metrics document.

The measured numbers in ``docs/_generated/gate-metrics.md`` come from one
recorded run of the canonical gate. This script never invents a runtime: an arm
missing from the receipt is reported as not recorded. Test counts are derived
from the current suite with ``pytest --collect-only``.

Refresh after changing the gate or the test selection::

    uv run python scripts/release_check.py --arm all --arm test \
        --timings docs/_generated/gate-timings.json
    uv run python scripts/gate_metrics.py
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECEIPT = ROOT / "docs" / "_generated" / "gate-timings.json"
OUTPUT = ROOT / "docs" / "_generated" / "gate-metrics.md"
SCHEMA = "activeblockference-gate/v1"
FAST_SELECTION = "not slow"

ARM_ORDER = (
    "lint",
    "types",
    "test",
    "test-full",
    "docs",
    "manuscript",
    "gnn",
    "smoke",
    "package",
    "render",
)


def _collected(*extra: str) -> int:
    """Return the number of tests selected by ``pytest --collect-only``."""

    result = subprocess.run(
        ["uv", "run", "pytest", "--collect-only", "-q", *extra],
        cwd=ROOT,
        check=True,
        text=True,
        capture_output=True,
    )
    return sum(1 for line in result.stdout.splitlines() if "::" in line)


def _receipt() -> dict[str, object]:
    """Return the recorded gate receipt, failing when it is absent or unknown."""

    if not RECEIPT.is_file():
        raise FileNotFoundError(
            f"missing gate receipt {RECEIPT.relative_to(ROOT)}; run "
            "scripts/release_check.py --timings docs/_generated/gate-timings.json"
        )
    payload = json.loads(RECEIPT.read_text(encoding="utf-8"))
    if payload.get("schema") != SCHEMA:
        raise ValueError(f"unsupported gate receipt schema {payload.get('schema')!r}")
    return payload


def render(payload: dict[str, object]) -> str:
    """Render the metrics document for one gate receipt."""

    arms = payload.get("arms") or {}
    tests = payload.get("tests") or {}
    lines = [
        "# Gate metrics",
        "",
        "<!-- Generated by scripts/gate_metrics.py; edit the script, not this file. -->",
        "",
        "Measured numbers from one recorded run of the canonical gate on "
        f"`{payload.get('host')}` with Python {payload.get('python')} at "
        f"`{payload.get('generated')}`.",
        "",
        "Refresh with:",
        "",
        "```bash",
        "uv run python scripts/release_check.py --arm all --arm test \\",
        "    --timings docs/_generated/gate-timings.json",
        "uv run python scripts/gate_metrics.py",
        "```",
        "",
        "## Arm wall times",
        "",
        "| Arm | Wall seconds | Status | First command |",
        "| --- | --- | --- | --- |",
    ]
    for arm in ARM_ORDER:
        entry = arms.get(arm)
        if not entry:
            lines.append(f"| `{arm}` | not recorded | — | — |")
            continue
        commands = entry.get("commands") or []
        command = f"`{commands[0]}`" if commands else "—"
        lines.append(f"| `{arm}` | {entry.get('seconds')} | {entry.get('status')} | {command} |")
    lines += ["", "## Test selection", "", "| Selection | Collected tests |", "| --- | --- |"]
    total = _collected()
    slow = _collected("-m", "slow")
    lines.append(f"| full suite | {total} |")
    lines.append(f'| fast (`-m "{FAST_SELECTION}"`) | {total - slow} |')
    lines.append(f"| slow (`-m slow`) | {slow} |")
    lines += [
        "",
        f"Recorded run: {tests.get('passed', 'not recorded')} passed, "
        f"{tests.get('skipped', 'not recorded')} skipped.",
        "",
    ]
    coverage = tests.get("coverage_percent")
    if coverage is None:
        lines.append("Coverage was not recorded by the receipt.")
    else:
        lines.append(
            f"`test-full` recorded {coverage}% line coverage of `blockference` (floor 90%)."
        )
    lines += [
        "",
        "## Receipt",
        "",
        "The source of these numbers is [`gate-timings.json`](gate-timings.json), "
        "written by `scripts/release_check.py --timings`. An arm absent from that "
        "receipt is reported as not recorded, never as passing.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Write the metrics document, or verify it with ``--check``."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the document is stale")
    args = parser.parse_args(argv)
    try:
        content = render(_receipt())
    except (FileNotFoundError, ValueError, subprocess.CalledProcessError) as exc:
        print(f"gate metrics failed: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if not OUTPUT.is_file():
            print(f"gate metrics failed: missing {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        if OUTPUT.read_text(encoding="utf-8") != content:
            print(
                "gate metrics drift: run uv run python scripts/gate_metrics.py to refresh "
                f"{OUTPUT.relative_to(ROOT)}",
                file=sys.stderr,
            )
            return 1
        print("gate metrics check passed")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
